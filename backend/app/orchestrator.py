logger = logging.getLogger("app.orchestrator")


class TurnError(Exception):
    """A turn that cannot be served; the route maps it to an HTTP status."""

    def __init__(self, status_code: int, detail: str) -> None:
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


class TurnLogger:
    """Opt-in per-turn research log (R4): one JSON line per turn. A failed write never fails a turn."""

    def __init__(self, path: Path) -> None:
        self.path = Path(path)

    def __call__(self, record: dict[str, Any]) -> None:
        try:
            with open(self.path, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(record, ensure_ascii=False) + "\n")
        except Exception as exc:  # the turn must still succeed
            logger.error("turn log write failed (%s); continuing", type(exc).__name__)


@dataclass
class Deps:
    """Process-lifetime, read-only collaborators. Injected so tests stay deterministic."""

    model: LoadedModel
    cfg: EngineConfig
    templates: TemplateFallback
    provider: str  # "template" | "mock" | "ollama"
    adapter: LLMAdapter | None = None
    # one number: the setting's declared default (S10; it had drifted from 14.0 to 18.0)
    llm_timeout_s: float = Settings.model_fields["LLM_TIMEOUT_S"].default
    # meta.llm: "template", "mock" or f"ollama:{LLM_MODEL}" (also on a fallback turn, where
    # meta.fallback says the template was served). Defaults to `provider`.
    llm_label: str | None = None
    # T1 (thinking mode): its own adapter, timeout and label; None unless the provider is "ollama".
    thinking_adapter: LLMAdapter | None = None
    thinking_timeout_s: float = Settings.model_fields["LLM_THINKING_TIMEOUT_S"].default
    thinking_label: str | None = None
    weak_threshold: int = 3
    now: Callable[[], datetime] = utc_now
    new_episode_id: Callable[[], str] = default_episode_id
    turn_logger: Callable[[dict[str, Any]], None] | None = None


def _ms(start: float, end: float) -> float:
    return max(0.0, (end - start) * 1000.0)


def _fixed_text(action: str, winning_strategy: str | None) -> str:
    if action == "offer_new_cycle":
        return fixed_copy.OFFER_NEW_CYCLE
    if action == "end_unresolved":
        return fixed_copy.END_UNRESOLVED
    if action == "clarify":
        return fixed_copy.CLARIFY
    return fixed_copy.resolved_text(winning_strategy)  # resolved


def _consecutive_student_turns(history) -> int:
    return sum(1 for prev, cur in zip(history, history[1:]) if prev.role == "student" and cur.role == "student")


def _thinking_turn(req: TutorRequest, deps: Deps) -> bool:
    """A thinking turn is generated by the thinking adapter: asked for, on the ollama provider, adapter built."""
    return bool(req.thinking) and deps.provider == "ollama" and deps.thinking_adapter is not None


async def _explain_text(req: TutorRequest, deps: Deps, strategy: str, state) -> tuple[str, bool, float]:
    """Returns (text, fallback, llm_ms). A generated reply is served only if `would_ship` says so;
    otherwise the template is served (fallback True) with ONE warning naming the reason. The warning
    never contains the student text or the model output."""
    started = time.perf_counter()
    if deps.provider == "template":
        text = deps.templates.get(req.topic, strategy, state.cycle)
        return text, True, _ms(started, time.perf_counter())
    try:
        priors = same_strategy_priors(
            [u.strategy for u in state.strategies_used], state.prior_explanations, strategy
        )
        if priors is None:
            logger.warning(
                "cannot pair prior_explanations with strategies_used (episode %s: %d priors, %d uses); "
                "passing every prior explanation",
                state.episode_id, len(state.prior_explanations), len(state.strategies_used),
            )
            priors = list(state.prior_explanations)
        prompt = build_prompt(
            topic=req.topic,
            strategy=strategy,
            cycle=state.cycle,
            student_message=req.message,
            prior_explanations=priors,
            conversation=req.history,  # M1: the generator sees the episode so far; classify never does
        )
        thinking = _thinking_turn(req, deps)
        adapter = deps.thinking_adapter if thinking else deps.adapter
        timeout_s = deps.thinking_timeout_s if thinking else deps.llm_timeout_s
        completion = await asyncio.wait_for(adapter.complete(prompt, timeout_s), timeout_s)
        if would_ship(completion.text, strategy, completion.truncated):
            text = finalise(completion.text, strategy, completion.truncated)
            return text, False, _ms(started, time.perf_counter())
        reason = "reasoning_leak" if reasoning_leak(finalise(completion.text, strategy, completion.truncated)) else "not_usable"
    except (asyncio.TimeoutError, TimeoutError):
        reason = "timeout"
    except Exception as exc:  # any other failure: the error TYPE only, never its message (it may echo text)
        reason = type(exc).__name__
    logger.warning(
        "LLM reply not served (%s); serving the template fallback (topic=%s strategy=%s cycle=%d)",
        reason, req.topic, strategy, state.cycle,
    )
    text = deps.templates.get(req.topic, strategy, state.cycle)
    return text, True, _ms(started, time.perf_counter())


async def handle_turn(req: TutorRequest, deps: Deps) -> TutorResponse:
    t0 = time.perf_counter()
    detected = detect_request(req.message)

    # Classify the current message only, raw (C2).
    c0 = time.perf_counter()
    result = classify(deps.model, req.message)
    classify_ms = _ms(c0, time.perf_counter())

    # Confusion override (lead ruling): see the comment in the engine's Tier 2 branch. RULE-layer
    # confusion only; never the model's.
    request_is_confusion = (
        detected is not None and result.source == "rule" and result.label == "confused"
    )
    try:
        decision = next_action(
            req.state, result.label, detected, req.message, deps.cfg, deps.new_episode_id,
            request_is_confusion=request_is_confusion, label_source=result.source,
        )
    except InvalidStateError as exc:
        raise TurnError(422, str(exc)) from exc

    state = decision.updated_state
    consecutive = _consecutive_student_turns(req.history)
    if consecutive:
        # A failed send followed by a retry leaves these behind. Designed flow: accepted. Never the text.
        logger.warning("episode %s: %d consecutive student turn(s) in history", state.episode_id, consecutive)

    # Text.
    if decision.action == "explain":
        text, fallback, llm_ms = await _explain_text(req, deps, decision.strategy, state)
        # The engine leaves prior_explanations alone on purpose; the prompt builder needs it from
        # cycle 2 to avoid repeating itself (claim C3, LLM path).
        state = state.model_copy(update={"prior_explanations": [*state.prior_explanations, text]})
    else:
        text = _fixed_text(decision.action, decision.winning_strategy)
        fallback = deps.provider == "template"
        llm_ms = 0.0

    # Terminal: the episode log, from the ECHOED state and history.
    episode_log = None
    if decision.action in ("resolved", "end_unresolved"):
        try:
            episode_log = build_episode_log(
                decision=decision,
                state=req.state,
                history=req.history,
                current_reaction=result,
                classify_fn=lambda t: classify(deps.model, t),
                student_id=req.student_id,
                topic=req.topic,
                model_version=deps.model.version,
                weak_threshold=deps.weak_threshold,
                now=deps.now,
            )
        except (EpisodeLogError, ValidationError) as exc:
            raise TurnError(422, f"cannot build the episode log: {exc}") from exc

    response = TutorResponse(
        request_id=req.request_id,
        confusion=ConfusionResult(label=result.label, probability=result.probability, source=result.source),
        detected_request=detected,
        action=decision.action,
        strategy=decision.strategy,
        trigger=decision.trigger,
        response=text,
        updated_state=state,
        episode_log=episode_log,
        meta=ResponseMeta(
            model_version=deps.model.version,
            llm=(deps.thinking_label if _thinking_turn(req, deps) else deps.llm_label) or deps.provider,
            latency_ms=LatencyBreakdown(
                classify=classify_ms, llm=llm_ms, total=_ms(t0, time.perf_counter())
            ),
            fallback=fallback,
            resolution_declined=decision.resolution_declined,
            thinking=req.thinking,
        ),
    )
    # No student text in either line (the opt-in turn log is the place for text).
    if decision.resolution_declined == "question_guard":
        logger.info("R6 question guard: resolution declined (episode %s)", state.episode_id)
    elif decision.resolution_declined == "model_understood_not_trusted":
        logger.info("R7: model-only understood not trusted, resolution declined (episode %s)", state.episode_id)

    if deps.turn_logger is not None:
        preceding = next((t.text for t in reversed(req.history) if t.role == "tutor"), None)
        deps.turn_logger(
            {
                "ts": deps.now().isoformat(),
                "episode_id": state.episode_id,
                "student_id": req.student_id,
                "topic": req.topic,
                "message": req.message,
                "preceding_tutor_turn": preceding,
                "label": result.label,
                "probability": result.probability,
                "source": result.source,
                "matched_phrase": result.matched_phrase,
                "model_label": result.model_label,
                "disagreement": result.model_label != result.label,
                "detected_request": detected,
                "action": decision.action,
                "strategy": decision.strategy,
                "trigger": decision.trigger,
                "cycle": state.cycle,
                "question_guard": decision.resolution_declined == "question_guard",
                "model_understood_guard": decision.resolution_declined == "model_understood_not_trusted",
                "thinking": req.thinking,
            }
        )
    return response
